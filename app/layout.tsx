import type { Metadata } from "next";
import { Plus_Jakarta_Sans } from "next/font/google";
import { ThemeProvider } from "next-themes";
import "./globals.css";
import Header from "../components/Header";
import SideBarServer from "@/components/SideBarServer";
import { getUserId } from "@/app/lib/session";
import { initializeUserBoards } from "@/app/lib/mongodb";

const Jakarta = Plus_Jakarta_Sans({
  subsets: ["latin"],
});

export const metadata: Metadata = {
  title: "Kanban Task Management",
  description: "Generated by create next app",
};

async function InitializeBoards() {
  const userId = await getUserId();
  await initializeUserBoards(userId);
  return null;
}

export default async function RootLayout({
  children,
}: {
  children: React.ReactNode;
}) {
  // Initialize boards for new users
  await InitializeBoards();

  return (
    <html lang="en" suppressHydrationWarning>
      <body className={`${Jakarta.className} antialiased`}>
        <ThemeProvider attribute="class" defaultTheme="system" enableSystem>
          <div className="min-h-screen md:flex">
            <div className="flex-1 flex flex-col min-w-0">
              <Header />
              <div className="flex flex-1 overflow-hidden">
                <SideBarServer />
                <main
                  className="flex-1 bg-[#f4f7fd] overflow-y-auto overflow-x-auto
                  dark:bg-[#20212c] transition-all duration-300"
                >
                  {children}
                </main>
              </div>
            </div>
          </div>
        </ThemeProvider>
      </body>
    </html>
  );
}
